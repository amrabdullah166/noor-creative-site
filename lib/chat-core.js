const hits = new Map();
const json = (o, status = 200) => new Response(JSON.stringify(o), { status, headers: { 'Content-Type': 'application/json; charset=utf-8', 'Cache-Control': 'no-store' } });

export async function handleChat(request, env = {}) {
  if (request.method !== 'POST') return json({ error: 'method' }, 405);
  const key = env.OPENAI_API_KEY;
  if (!key) return json({ error: 'not_configured' }, 503);
  const MODEL = env.OPENAI_MODEL || 'gpt-4o-mini';

  // حدّ بسيط: 20 رسالة بالدقيقة لكل زائر
  const ip = request.headers.get('cf-connecting-ip') || 'anon';
  const now = Date.now(), win = (hits.get(ip) || []).filter(t => now - t < 60000);
  if (win.length >= 20) return json({ error: 'rate_limited' }, 429);
  win.push(now); hits.set(ip, win);

  let body;
  try { body = await request.json(); } catch { return json({ error: 'bad_json' }, 400); }
  const msgs = (Array.isArray(body?.messages) ? body.messages : [])
    .filter(m => m && (m.role === 'user' || m.role === 'assistant') && typeof m.content === 'string' && m.content.trim())
    .slice(-14)
    .map(m => ({ role: m.role, content: m.content.slice(0, 1500) }));
  if (!msgs.length || msgs[msgs.length - 1].role !== 'user') return json({ error: 'bad_request' }, 400);
  const page = typeof body.page === 'string' ? body.page.slice(0, 60) : '';

  let r;
  try {
    r = await fetch('https://api.openai.com/v1/chat/completions', {
      method: 'POST',
      headers: { Authorization: `Bearer ${key}`, 'Content-Type': 'application/json' },
      body: JSON.stringify({
        model: MODEL, stream: true, temperature: 0.5, max_tokens: 450,
        messages: [{ role: 'system', content: SYSTEM + (page ? `\n\nالزائر يتصفح الآن: ${page}` : '') }, ...msgs]
      })
    });
  } catch (e) { console.error('fetch failed', e); return json({ error: 'upstream' }, 502); }
  if (!r.ok) {
    const raw = await r.text(); console.error('openai', r.status, raw);
    let code = ''; try { const e = JSON.parse(raw)?.error; code = e?.code || e?.type || ''; } catch {}
    return json({ error: 'upstream', status: r.status, code }, 502);
  }

  // تحويل SSE من OpenAI إلى نص متدفق بسيط
  const enc = new TextEncoder(), dec = new TextDecoder();
  let buf = '';
  const out = r.body.pipeThrough(new TransformStream({
    transform(chunk, ctrl) {
      buf += dec.decode(chunk, { stream: true });
      const lines = buf.split('\n'); buf = lines.pop();
      for (const line of lines) {
        const s = line.trim();
        if (!s.startsWith('data:')) continue;
        const d = s.slice(5).trim();
        if (d === '[DONE]') continue;
        try { const t = JSON.parse(d).choices?.[0]?.delta?.content; if (t) ctrl.enqueue(enc.encode(t)); } catch {}
      }
    }
  }));
  return new Response(out, { headers: { 'Content-Type': 'text/plain; charset=utf-8', 'Cache-Control': 'no-store', 'X-Content-Type-Options': 'nosniff' } });
}
